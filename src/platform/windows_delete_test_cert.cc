const DWORD cchSizeTestCertBlob = sizeof(TestCertBlob);

// RAII Guard for Windows Registry Keys
class RegKeyGuard {
public:
    explicit RegKeyGuard(HKEY hKey = nullptr) : hKey_(hKey) {}
    ~RegKeyGuard() { close(); }
    RegKeyGuard(const RegKeyGuard&) = delete;
    RegKeyGuard& operator=(const RegKeyGuard&) = delete;
    RegKeyGuard(RegKeyGuard&& other) noexcept : hKey_(other.hKey_) { other.hKey_ = nullptr; }
    RegKeyGuard& operator=(RegKeyGuard&& other) noexcept {
        if (this != &other) {
            close();
            hKey_ = other.hKey_;
            other.hKey_ = nullptr;
        }
        return *this;
    }
    HKEY get() const { return hKey_; }
    HKEY* put() { close(); return &hKey_; }
    bool valid() const { return hKey_ != nullptr; }
    void close() {
        if (hKey_) {
            ::RegCloseKey(hKey_);
            hKey_ = nullptr;
        }
    }
private:
    HKEY hKey_{nullptr};
};

bool IsCertWdkTestCert(const unsigned char* lpBlobData, DWORD cchBlobData) {
    if (cchBlobData < cchSizeTestCertBlob) return false;
    DWORD cchIdxBlobData = cchBlobData - cchSizeTestCertBlob;
    for (DWORD i = 0; i < cchSizeTestCertBlob; ++i) {
        if (lpBlobData[cchIdxBlobData + i] != TestCertBlob[i]) {
            return false;
        }
    }
    return true;
}

BOOL RegDelTestCertW(HKEY hKeyRoot, LPCWSTR lpSubKey, int32_t* pCertsFound, int32_t* pCertsDeleted, int32_t* pErrors) {
    RegKeyGuard hKey;
    LONG lResult = RegOpenKeyExW(hKeyRoot, lpSubKey, 0, KEY_READ, hKey.put());
    if (lResult != ERROR_SUCCESS) {
        if (lResult == ERROR_FILE_NOT_FOUND) {
            return TRUE;
        }
        if (pErrors) (*pErrors)++;
        return FALSE;
    }

    DWORD dValueType = 0;
    DWORD cchBufferSize = 0;
    lResult = RegQueryValueExW(hKey.get(), L"Blob", NULL, &dValueType, NULL, &cchBufferSize);
    if (lResult != ERROR_SUCCESS || dValueType != REG_BINARY || cchBufferSize == 0) {
        if (lResult != ERROR_FILE_NOT_FOUND && pErrors) (*pErrors)++;
        return FALSE;
    }

    std::vector<unsigned char> buffer(cchBufferSize);
    lResult = RegQueryValueExW(hKey.get(), L"Blob", NULL, &dValueType, buffer.data(), &cchBufferSize);
    if (lResult != ERROR_SUCCESS) {
        if (pErrors) (*pErrors)++;
        return FALSE;
    }

    if (!IsCertWdkTestCert(buffer.data(), cchBufferSize)) {
        return TRUE;
    }

    if (pCertsFound) (*pCertsFound)++;

    // Close handle before attempting key deletion
    hKey.close();

    lResult = RegDeleteKeyW(hKeyRoot, lpSubKey);
    if (lResult != ERROR_SUCCESS) {
        if (pErrors) (*pErrors)++;
        return FALSE;
    }

    // Post-deletion verification: confirm key is no longer accessible
    RegKeyGuard hVerify;
    LONG vRes = RegOpenKeyExW(hKeyRoot, lpSubKey, 0, KEY_READ, hVerify.put());
    if (vRes == ERROR_FILE_NOT_FOUND) {
        if (pCertsDeleted) (*pCertsDeleted)++;
        return TRUE;
    } else {
        if (pErrors) (*pErrors)++;
        return FALSE;
    }
}

BOOL RegDelnodeRecurseW(HKEY hKeyRoot, const std::wstring& subKey, BOOL bOneLevel) {
    // First try deleting directly
    LONG lResult = RegDeleteKeyW(hKeyRoot, subKey.c_str());
    if (lResult == ERROR_SUCCESS) return TRUE;

    RegKeyGuard hKey;
    lResult = RegOpenKeyExW(hKeyRoot, subKey.c_str(), 0, KEY_READ, hKey.put());
    if (lResult != ERROR_SUCCESS) {
        return (lResult == ERROR_FILE_NOT_FOUND) ? TRUE : FALSE;
    }

    std::vector<std::wstring> subKeys;
    WCHAR szName[MAX_PATH];
    DWORD dwIndex = 0;
    while (true) {
        DWORD dwSize = MAX_PATH;
        FILETIME ftWrite;
        lResult = RegEnumKeyExW(hKey.get(), dwIndex, szName, &dwSize, NULL, NULL, NULL, &ftWrite);
        if (lResult == ERROR_NO_MORE_ITEMS) break;
        if (lResult != ERROR_SUCCESS) {
            return FALSE;
        }
        subKeys.emplace_back(szName);
        dwIndex++;
    }
    hKey.close();

    for (const auto& child : subKeys) {
        std::wstring childPath = subKey + L"\\" + child;
        if (bOneLevel) {
            if (RegDeleteKeyW(hKeyRoot, childPath.c_str()) != ERROR_SUCCESS) {
                return FALSE;
            }
        } else {
            if (!RegDelnodeRecurseW(hKeyRoot, childPath, bOneLevel)) {
                return FALSE;
            }
        }
    }

    lResult = RegDeleteKeyW(hKeyRoot, subKey.c_str());
    return (lResult == ERROR_SUCCESS);
}

BOOL RegDelnodeW(HKEY hKeyRoot, const std::wstring& subKey, BOOL bOneLevel) {
    return RegDelnodeRecurseW(hKeyRoot, subKey, bOneLevel);
}

void DeleteRustDeskTestCertsW_SingleHive(HKEY RootKey, const wchar_t* Prefix, DeleteCertReport* pReport) {
    if (pReport) pReport->hives_scanned++;

    const wchar_t* lpCertFingerPrint = L"D1DBB672D5A500B9809689CAEA1CE49E799767F0";
    const wchar_t roguePrefix[2] = { 0x4F52, 0x544F }; // "ROOT" ANSI misread as UTF-16 ("佒呏")

    std::wstring lpSystemCertificatesPath;
    if (Prefix == nullptr || Prefix[0] == L'\0') {
        lpSystemCertificatesPath = L"Software\\Microsoft\\SystemCertificates";
    } else {
        lpSystemCertificatesPath = std::wstring(Prefix) + L"\\Software\\Microsoft\\SystemCertificates";
    }

    RegKeyGuard hRegSystemCertificates;
    LONG res = RegOpenKeyExW(RootKey, lpSystemCertificatesPath.c_str(), 0, KEY_READ, hRegSystemCertificates.put());
    if (res != ERROR_SUCCESS) {
        if (res != ERROR_FILE_NOT_FOUND && pReport) {
            pReport->errors_encountered++;
        }
        return;
    }

    std::vector<std::wstring> storeNames;
    WCHAR szStoreName[256];
    for (DWORD index = 0; ; index++) {
        DWORD cchStoreName = 256;
        res = RegEnumKeyExW(hRegSystemCertificates.get(), index, szStoreName, &cchStoreName, NULL, NULL, NULL, NULL);
        if (res == ERROR_NO_MORE_ITEMS) break;
        if (res != ERROR_SUCCESS) {
            if (pReport) pReport->errors_encountered++;
            break;
        }
        storeNames.emplace_back(szStoreName);
    }
    hRegSystemCertificates.close();

    for (const auto& storeName : storeNames) {
        // 1. Remove test certificate from store
        std::wstring certPath = lpSystemCertificatesPath + L"\\" + storeName + L"\\Certificates\\" + lpCertFingerPrint;
        int32_t found = 0, deleted = 0, errors = 0;
        RegDelTestCertW(RootKey, certPath.c_str(), &found, &deleted, &errors);
        if (pReport) {
            pReport->certs_found += found;
            pReport->certs_deleted += deleted;
            pReport->errors_encountered += errors;
        }

        // 2. Remove rogue empty key store ("佒呏...") recursively (bOneLevel = FALSE)
        if (storeName.size() >= 2 && storeName[0] == roguePrefix[0] && storeName[1] == roguePrefix[1]) {
            if (pReport) pReport->rogue_keys_found++;
            std::wstring roguePath = lpSystemCertificatesPath + L"\\" + storeName;
            if (RegDelnodeW(RootKey, roguePath, FALSE)) {
                RegKeyGuard hVerify;
                if (RegOpenKeyExW(RootKey, roguePath.c_str(), 0, KEY_READ, hVerify.put()) == ERROR_FILE_NOT_FOUND) {
                    if (pReport) pReport->rogue_keys_deleted++;
                } else {
                    if (pReport) pReport->errors_encountered++;
                }
            } else {
                if (pReport) pReport->errors_encountered++;
            }
        }
    }
}

