extern "C" DeleteCertReport DeleteRustDeskTestCertsWithReport() {
    DeleteCertReport report = {1, 0, 0, 0, 0, 0, 0};

    // 1. Current user
    DeleteRustDeskTestCertsW_SingleHive(HKEY_CURRENT_USER, nullptr, &report);

    // 2. Local machine
    DeleteRustDeskTestCertsW_SingleHive(HKEY_LOCAL_MACHINE, nullptr, &report);

    // 3. All users under HKEY_USERS
    RegKeyGuard hRegUsers;
    LONG res = RegOpenKeyExW(HKEY_USERS, nullptr, 0, KEY_READ, hRegUsers.put());
    if (res == ERROR_SUCCESS) {
        std::vector<std::wstring> userSids;
        WCHAR szUserSid[256];
        for (DWORD index = 0; ; index++) {
            DWORD cchUserSid = 256;
            res = RegEnumKeyExW(hRegUsers.get(), index, szUserSid, &cchUserSid, NULL, NULL, NULL, NULL);
            if (res == ERROR_NO_MORE_ITEMS) break;
            if (res != ERROR_SUCCESS) break;
            userSids.emplace_back(szUserSid);
        }
        hRegUsers.close();

        for (const auto& sid : userSids) {
            DeleteRustDeskTestCertsW_SingleHive(HKEY_USERS, sid.c_str(), &report);
        }
    }

    if (report.errors_encountered > 0 ||
        (report.certs_found != report.certs_deleted) ||
        (report.rogue_keys_found != report.rogue_keys_deleted)) {
        report.success = 0;
    }
    return report;
}

extern "C" int DeleteRustDeskTestCertsW() {
    DeleteCertReport report = DeleteRustDeskTestCertsWithReport();
    return (report.success != 0 && report.errors_encountered == 0) ? 0 : 1;
}
